/**
 * Generates public/sitemap.xml and public/robots.txt from the real page data.
 *
 * Run via `npm run seo:generate` (wired into `prebuild`, so a deploy can never
 * ship a sitemap that disagrees with the routes). Relies on Node's native
 * TypeScript type-stripping (Node >= 22.6) to import the data modules directly
 * rather than keeping a second copy of the slug list.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Resolve the production origin.
 *
 * On Vercel, VERCEL_PROJECT_PRODUCTION_URL is injected at build time and is
 * always the PRODUCTION domain (never the per-deployment preview URL), so the
 * first real deploy corrects the origin on its own — no code change, no manual
 * confirmation. SITE_URL wins if it is set explicitly. Locally, neither exists
 * and we fall back to the literal in src/data/site.ts.
 *
 * The resolved value is written to src/data/site-origin.ts so the app and the
 * sitemap can never disagree about what the canonical origin is.
 */
function resolveOrigin() {
  const explicit = process.env.SITE_URL ?? process.env.VITE_SITE_URL;
  if (explicit) return { origin: explicit.replace(/\/+$/, ""), source: "SITE_URL env" };

  const vercel = process.env.VERCEL_PROJECT_PRODUCTION_URL;
  if (vercel) {
    const host = vercel.replace(/^https?:\/\//, "").replace(/\/+$/, "");
    if (host) return { origin: `https://${host}`, source: "VERCEL_PROJECT_PRODUCTION_URL" };
  }

  const siteSrc = readFileSync(resolve(root, "src/data/site.ts"), "utf8");
  const m = siteSrc.match(/const SITE_URL_FALLBACK\s*=\s*["'`]([^"'`]+)["'`]/);
  if (!m) throw new Error("Could not find SITE_URL_FALLBACK in src/data/site.ts");
  return { origin: m[1].replace(/\/+$/, ""), source: "fallback literal (not yet verified)" };
}

const { origin: ORIGIN, source: ORIGIN_SOURCE } = resolveOrigin();

writeFileSync(
  resolve(root, "src/data/site-origin.ts"),
  `// GENERATED by scripts/generate-seo-files.mjs — do not edit by hand.
// Resolved at build time from: ${ORIGIN_SOURCE}
export const SITE_ORIGIN = ${JSON.stringify(ORIGIN)};
export const SITE_ORIGIN_SOURCE = ${JSON.stringify(ORIGIN_SOURCE)};
`,
);

const { cities } = await import(resolve(root, "src/data/cities.ts"));
const { seoServices } = await import(resolve(root, "src/data/services-seo.ts"));
const { breeds } = await import(resolve(root, "src/data/breeds.ts"));
const { cityServices } = await import(resolve(root, "src/data/city-services.ts"));
const { guides } = await import(resolve(root, "src/data/guides.ts"));

const today = new Date().toISOString().slice(0, 10);

/** priority/changefreq are hints only, but they cost nothing and help big sites. */
const urls = [
  { loc: "/", priority: "1.0", changefreq: "weekly" },
  { loc: "/services", priority: "0.9", changefreq: "monthly" },
  { loc: "/locations", priority: "0.9", changefreq: "monthly" },
  { loc: "/breeds", priority: "0.9", changefreq: "monthly" },
  { loc: "/pricing", priority: "0.9", changefreq: "monthly" },
  { loc: "/guides", priority: "0.9", changefreq: "monthly" },
  { loc: "/about", priority: "0.8", changefreq: "yearly" },
  { loc: "/contact", priority: "0.8", changefreq: "yearly" },
  { loc: "/privacy", priority: "0.3", changefreq: "yearly" },
  { loc: "/terms", priority: "0.3", changefreq: "yearly" },
  ...seoServices.map((s) => ({
    loc: `/services/${s.slug}`,
    priority: "0.8",
    changefreq: "monthly",
  })),
  ...cities.map((c) => ({
    loc: `/pet-grooming/${c.slug}`,
    priority: "0.8",
    changefreq: "monthly",
  })),
  ...breeds.map((b) => ({
    loc: `/breeds/${b.slug}`,
    priority: "0.7",
    changefreq: "monthly",
  })),
  ...cityServices.map((cs) => ({
    loc: `/pet-grooming/${cs.citySlug}/${cs.serviceSlug}`,
    priority: "0.7",
    changefreq: "monthly",
  })),
  ...guides.map((g) => ({ loc: `/guides/${g.slug}`, priority: "0.7", changefreq: "monthly" })),
];

const seen = new Set();
for (const u of urls) {
  if (seen.has(u.loc)) throw new Error(`Duplicate sitemap URL: ${u.loc}`);
  seen.add(u.loc);
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${ORIGIN}${u.loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join("\n")}
</urlset>
`;

const robots = `User-agent: *
Allow: /

Sitemap: ${ORIGIN}/sitemap.xml
`;

writeFileSync(resolve(root, "public/sitemap.xml"), sitemap);
writeFileSync(resolve(root, "public/robots.txt"), robots);

console.log(
  `sitemap.xml  ${urls.length} URLs (${cities.length} cities, ${seoServices.length} services, ` +
    `${breeds.length} breeds, ${cityServices.length} city+service, ${guides.length} guides`,
);
console.log(`robots.txt   origin ${ORIGIN}  (source: ${ORIGIN_SOURCE})`);
